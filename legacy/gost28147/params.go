package gost28147

// Именованные наборы подстановок.
//
// Стандарт ГОСТ 28147-89 не задаёт S-блоки: они считаются долговременным
// ключевым элементом. Приведённые ниже наборы взяты из RFC 4357,
// раздел 11 (структуры ASN.1 с упакованными таблицами) и из RFC 7836,
// приложение C.
//
// Каждый набор возвращается копией: таблицы неизменяемы для вызывающего
// кода, случайная правка одного набора не может испортить другой.

func clone(s SBox) *SBox {
	out := s
	return &out
}

// ParamTest возвращает id-Gost28147-89-TestParamSet (RFC 4357).
// Предназначен только для проверки реализации.
func ParamTest() *SBox { return clone(sboxTest) }

// ParamCryptoProA возвращает id-Gost28147-89-CryptoPro-A-ParamSet.
func ParamCryptoProA() *SBox { return clone(sboxCryptoProA) }

// ParamCryptoProB возвращает id-Gost28147-89-CryptoPro-B-ParamSet.
func ParamCryptoProB() *SBox { return clone(sboxCryptoProB) }

// ParamCryptoProC возвращает id-Gost28147-89-CryptoPro-C-ParamSet.
func ParamCryptoProC() *SBox { return clone(sboxCryptoProC) }

// ParamCryptoProD возвращает id-Gost28147-89-CryptoPro-D-ParamSet.
func ParamCryptoProD() *SBox { return clone(sboxCryptoProD) }

// ParamZ возвращает id-tc26-gost-28147-param-Z (RFC 7836, приложение C) —
// тот самый набор, который зафиксирован в "Магме".
func ParamZ() *SBox { return clone(sboxZ) }

// ParamHashTest возвращает набор подстановок из
// id-GostR3411-94-TestParamSet. Он же напечатан явной таблицей в
// RFC 5831, п. 7.1, и используется в тамошних контрольных примерах.
func ParamHashTest() *SBox { return clone(sboxHashTest) }

// ParamHashCryptoPro возвращает набор подстановок из
// id-GostR3411-94-CryptoProParamSet — практически единственный, который
// встречается в реальных документах.
func ParamHashCryptoPro() *SBox { return clone(sboxHashCryptoPro) }

