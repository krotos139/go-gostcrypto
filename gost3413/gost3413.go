// Package gost3413 реализует режимы работы блочных шифров по
// ГОСТ Р 34.13-2015.
//
// Стандарт определяет шесть режимов: простой замены (ECB), гаммирования
// (CTR), гаммирования с обратной связью по выходу (OFB), простой замены с
// зацеплением (CBC), гаммирования с обратной связью по шифртексту (CFB) и
// выработки имитовставки (OMAC1, он же CMAC). Режимы работают с любым
// cipher.Block, в том числе с "Магмой" и "Кузнечиком" из пакета gost3412.
//
// # Отличия от crypto/cipher
//
// Одноимённые режимы стандартной библиотеки Go не подходят: у ГОСТ-версий
// есть параметры, которых в crypto/cipher нет.
//
//   - CTR: синхропосылка имеет длину n/2, а не n; счётчик занимает младшую
//     половину блока. Дополнительно поддерживается усечение гаммы до s < n.
//   - CBC и OFB: регистр сдвига имеет длину m = n*z, то есть синхропосылка
//     может занимать несколько блоков. При z = 1 поведение совпадает с
//     классическим.
//   - CFB: регистр сдвигается на s, а не на n.
//
// При s = n и z = 1 результаты обязаны совпадать со стандартными
// реализациями Go; это проверяется тестами.
//
// # Гранулярность параметров
//
// Стандарт задаёт s и m в битах и допускает любые значения 0 < s <= n.
// Здесь s и m задаются в байтах: побитовый интерфейс в Go неудобен и на
// практике не используется. Все контрольные примеры стандарта укладываются
// в байтовую гранулярность.
//
// # Выбор синхропосылок
//
// Требования из п. 4.2 стандарта — ответственность вызывающего кода:
//
//   - CBC и CFB: синхропосылка должна быть непредсказуемой (случайной или
//     псевдослучайной);
//   - CTR: все синхропосылки, использованные на одном ключе, должны быть
//     попарно различны;
//   - OFB: синхропосылка должна быть уникальной либо непредсказуемой.
//
// Режим простой замены синхропосылку не использует и не скрывает
// повторяющиеся блоки открытого текста.
package gost3413

import "errors"

var (
	// ErrIVSize возвращается, когда длина синхропосылки не соответствует
	// требованиям режима.
	ErrIVSize = errors.New("gost3413: недопустимая длина синхропосылки")
	// ErrSParam возвращается при недопустимом значении параметра s.
	ErrSParam = errors.New("gost3413: недопустимое значение параметра s")
	// ErrBlockSize возвращается, когда размер блока шифра не поддерживается
	// режимом.
	ErrBlockSize = errors.New("gost3413: неподдерживаемый размер блока")
)

// xorBytes записывает в dst побайтовое сложение a и b по модулю 2.
// Длина определяется по n; dst может совпадать с a или b.
func xorBytes(dst, a, b []byte, n int) {
	for i := 0; i < n; i++ {
		dst[i] = a[i] ^ b[i]
	}
}

// dup возвращает копию среза.
func dup(b []byte) []byte {
	out := make([]byte, len(b))
	copy(out, b)
	return out
}
